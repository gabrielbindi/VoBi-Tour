-- Tour
CREATE TABLE tour (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    date        date NOT NULL,
    status      text NOT NULL DEFAULT 'planned'
                CHECK (status IN ('planned', 'active', 'done')),
    cargo_type  cargo_type NOT NULL,
    counter     integer NOT NULL DEFAULT 0
                CHECK (counter >= 0)
);

-- Tour-Crew
CREATE TABLE tour_crew (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id       integer NOT NULL REFERENCES tour (id),
    crew_id       integer NOT NULL REFERENCES crew_member (id),
    co_driver_id  integer REFERENCES crew_member (id),
    started_at    timestamptz,
    finished_at   timestamptz,

    UNIQUE (tour_id, crew_id),
    CHECK (co_driver_id <> crew_id),
    CHECK (finished_at >= started_at)
);

-- Tour-Vehicle
CREATE TABLE tour_vehicle (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id      integer NOT NULL REFERENCES tour (id),
    vehicle_id   integer NOT NULL REFERENCES vehicle (id),
    assigned_at  timestamptz NOT NULL DEFAULT now()
);

-- Break
CREATE TABLE break (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id   integer NOT NULL REFERENCES tour (id),
    crew_id   integer NOT NULL REFERENCES crew_member (id),
    start     timestamptz NOT NULL,
    ended_at  timestamptz,

    CHECK (ended_at >= start)
);

-- Zone
CREATE TABLE zone (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id      integer NOT NULL REFERENCES tour (id),
    name         text,
    kind         text NOT NULL
                 CHECK (kind IN ('boundary', 'cluster', 'split', 'corridor')),
    sequence     integer,
    area         geometry(Polygon, 4326) NOT NULL,
    entry_point  geometry(Point, 4326),
    created_by   text NOT NULL
                 CHECK (created_by IN ('system', 'driver', 'dispatcher')),

    UNIQUE (id, tour_id)
);