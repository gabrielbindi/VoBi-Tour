-- Route
CREATE TABLE route (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id        integer NOT NULL REFERENCES tour (id),
    variant        text NOT NULL
                   CHECK (variant IN ('constrained', 'unconstrained')),
    is_active      boolean NOT NULL DEFAULT false,
    geom           geometry(LineString, 4326) NOT NULL,
    length_m       numeric(10,1) NOT NULL CHECK (length_m >= 0),
    duration_s     numeric(10,1) NOT NULL CHECK (duration_s >= 0),
    calculated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX route_one_active_per_tour ON route (tour_id) WHERE is_active;

-- Route-Warning
CREATE TABLE route_warning (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id          integer NOT NULL REFERENCES route (id),
    osm_way_id        bigint,
    from_node_osm_id  bigint,
    to_node_osm_id    bigint,
    kind              text NOT NULL
                      CHECK (kind IN ('underpass_no_height', 'missing_value', 'private_way')),
    severity          text NOT NULL
                      CHECK (severity IN ('info', 'warning', 'critical')),
    message           text NOT NULL,

    CHECK (num_nulls(osm_way_id, from_node_osm_id, to_node_osm_id) IN (0, 3))
);

-- Street-Attribute
CREATE TABLE street_attribute (
    osm_way_id        bigint NOT NULL,
    from_node_osm_id  bigint NOT NULL,
    to_node_osm_id    bigint NOT NULL,
    max_height        numeric(4,2) CHECK (max_height > 0),   -- m
    max_width         numeric(4,2) CHECK (max_width  > 0),   -- m
    max_weight        numeric(5,2) CHECK (max_weight > 0),   -- t
    width             numeric(5,2) CHECK (width      > 0),   -- m
    lanes             integer      CHECK (lanes      > 0),
    access            text,
    passes_under      boolean,

    PRIMARY KEY (osm_way_id, from_node_osm_id, to_node_osm_id)
);

-- Street-Override 
CREATE TABLE street_override (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    osm_way_id        bigint NOT NULL,
    from_node_osm_id  bigint NOT NULL,
    to_node_osm_id    bigint NOT NULL,
    serve_mode        text
                      CHECK (serve_mode IN ('both', 'direction_only')),
    max_height        numeric(4,2) CHECK (max_height > 0),
    max_width         numeric(4,2) CHECK (max_width  > 0),
    max_weight        numeric(5,2) CHECK (max_weight > 0),
    width             numeric(5,2) CHECK (width      > 0),
    lanes             integer      CHECK (lanes      > 0),
    access            text,
    passes_under      boolean,
    created_by        text NOT NULL
                      CHECK (created_by IN ('driver', 'dispatcher')),

    UNIQUE (osm_way_id, from_node_osm_id, to_node_osm_id)
);
