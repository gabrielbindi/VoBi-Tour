-- Route
CREATE TABLE route (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id        integer NOT NULL REFERENCES tour (id),
    variant        text NOT NULL
                   CHECK (variant IN ('constrained', 'unconstrained')),
    is_active      boolean NOT NULL DEFAULT false,
    geom           geometry(LineString, 4326) NOT NULL,
    length_m       numeric(10,1) NOT NULL CHECK (length_m >= 0),
    duration_s     numeric(10,1) NOT NULL CHECK (duration_s >= 0),
    calculated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX route_one_active_per_tour ON route (tour_id) WHERE is_active;

-- Route-Warning
CREATE TABLE route_warning (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id          integer NOT NULL REFERENCES route (id),
    osm_way_id        bigint,
    from_node_osm_id  bigint,
    to_node_osm_id    bigint,
    kind              text NOT NULL
                      CHECK (kind IN ('underpass_no_height', 'missing_value', 'private_way')),
    severity          text NOT NULL
                      CHECK (severity IN ('info', 'warning', 'critical')),
    message           text NOT NULL,

    CHECK (num_nulls(osm_way_id, from_node_osm_id, to_node_osm_id) IN (0, 3))
);
