-- Domain model for cargo_type
CREATE DOMAIN cargo_type AS text
    CHECK (VALUE IN ('paper', 'residual_waste', 'packaging', 'parcel', 'passenger'));

-- Crew-members

CREATE TABLE crew_member (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL,
    last_name       text NOT NULL,
    phone           text,
    service_number  text NOT NULL UNIQUE
);

-- Account
CREATE TABLE account (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        text NOT NULL UNIQUE,
    password_hash   text NOT NULL,
    role            text NOT NULL CHECK (role IN ('driver', 'dispatcher', 'admin')),
    crew_id         integer REFERENCES crew_member(id) ON DELETE SET NULL
);

-- vehicles

CREATE TABLE vehicle (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate   text NOT NULL UNIQUE,
    height  numeric(4,2) NOT NULL CHECK (height > 0),     -- m
    width   numeric(4,2) NOT NULL CHECK (width > 0),     -- m
    weight  numeric(5,2) NOT NULL CHECK (weight > 0)      -- t
);

-- clients

CREATE TABLE client (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   text NOT NULL,
    phone  text
);

-- locations

CREATE TABLE location (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_depot      boolean NOT NULL DEFAULT FALSE,
    note          text,
    geom          geometry(Point, 4326) NOT NULL,
    street        text NOT NULL,
    house_number  text,
    zip           text NOT NULL,
    city          text NOT NULL,
    -- Snapping to OSM nodes
    way_osm_id          bigint,
    from_node_osm_id    bigint,
    to_node_osm_id      bigint,
    edge_fraction       double precision CHECK (edge_fraction BETWEEN 0 AND 1),
    CHECK (num_nulls(way_osm_id, from_node_osm_id, to_node_osm_id, edge_fraction) = 0 OR num_nulls(way_osm_id, from_node_osm_id, to_node_osm_id, edge_fraction) = 4)
);

-- cargo

CREATE TABLE cargo (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id    integer NOT NULL REFERENCES client(id),
    location_id  integer NOT NULL REFERENCES location(id),
    typ          cargo_type NOT NULL,
    volume       integer CHECK (volume > 0)  -- l
);
