-- Stop
CREATE TABLE stop (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id          integer NOT NULL REFERENCES tour (id),
    location_id      integer NOT NULL REFERENCES location (id),
    zone_id          integer,
    sequence         integer,
    planned_arrival  timestamptz,
    status           text NOT NULL DEFAULT 'open'
                     CHECK (status IN ('open', 'done', 'skipped', 'reassigned')),
    side             text NOT NULL DEFAULT 'any'
                     CHECK (side IN ('left', 'right', 'any')),
    priority         integer,
    special_type     text
                     CHECK (special_type IN ('start', 'depot', 'end')),
    warning          text,

    FOREIGN KEY (zone_id, tour_id) REFERENCES zone (id, tour_id)
);

-- Stop-Crew
CREATE TABLE stop_crew (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_id                 integer NOT NULL REFERENCES stop (id),
    crew_id                 integer NOT NULL REFERENCES crew_member (id),
    originally_assigned_to  integer REFERENCES crew_member (id),
    arrived_at              timestamptz,
    finished_at             timestamptz,

    CHECK (originally_assigned_to <> crew_id),
    CHECK (finished_at >= arrived_at),
    CHECK (finished_at IS NULL OR arrived_at IS NOT NULL)
);

-- Problem
CREATE TABLE problem (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_id      integer NOT NULL REFERENCES stop (id),
    reported_by  integer NOT NULL REFERENCES crew_member (id),
    description  text NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    resolved_at  timestamptz,

    CHECK (resolved_at >= created_at),
    UNIQUE (id, stop_id)
);

-- Photo
CREATE TABLE photo (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid              uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    stop_id           integer NOT NULL REFERENCES stop (id),
    problem_id        integer,
    crew_id           integer NOT NULL REFERENCES crew_member (id),
    data              bytea NOT NULL,
    description       text,
    is_location_info  boolean NOT NULL DEFAULT false,
    created_at        timestamptz NOT NULL DEFAULT now(),

    FOREIGN KEY (problem_id, stop_id) REFERENCES problem (id, stop_id)
);