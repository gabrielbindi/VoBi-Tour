-- 001 init.sql
-- creates Tables

CREATE EXTENSION IF NOT EXISTS postgis;

-- Crew-members

CREATE TABLE crew_member (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text,
    last_name       text,
    phone           text,
    service_number  text
);

-- vehicles

CREATE TABLE vehicle (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate   varchar,
    height  integer,     -- cm
    width   integer,     -- cm
    weight  integer      -- kg
);

-- clients

CREATE TABLE client (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   text,
    phone  text
);

-- locations

CREATE TABLE location (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description   varchar,
    geom          geometry(Point, 4326),
    street        text,
    house_number  text,
    zip           text,
    city          text
);

-- tours

CREATE TABLE tour (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     text,
    date     date,
    status   varchar,
    counter  integer
);

-- stops
-- connection to -> tour (id)
-- connection to -> location (id)

CREATE TABLE stop (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id       integer NOT NULL REFERENCES tour(id),
    location_id   integer NOT NULL REFERENCES location(id),
    sequence      integer,
    arrival       time,
    status        varchar,
    is_special    boolean,
    priority      integer,
    special_type  text
);

-- breaks
-- connection to -> tour (id)
-- connection to -> crew_member (id)

CREATE TABLE break (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id  integer NOT NULL REFERENCES tour(id),
    crew_id  integer NOT NULL REFERENCES crew_member(id),
    start    time,
    "end"    time
);

-- tour_vehicle
-- Junction Table

-- connections to -> tour (id)
-- connections to -> vehicle (id)

CREATE TABLE tour_vehicle (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id        integer NOT NULL REFERENCES tour(id),
    vehicle_id     integer NOT NULL REFERENCES vehicle(id),
    assigned_date  date
);

-- tour_crew
-- Junction Table

-- connection to -> crew_member (id)
-- connection to -> tour (id)


CREATE TABLE tour_crew (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id        integer NOT NULL REFERENCES crew_member(id),
    tour_id        integer NOT NULL REFERENCES tour(id),
    co_driver_id   integer REFERENCES crew_member(id),
    assigned_date  date,
    started_at     time,
    finished_at    time,
    role           text
);

-- stop_crew
-- Junction Table

-- connection to -> stop (id)
-- connection to -> crew_member (id)

CREATE TABLE stop_crew (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_id                 integer NOT NULL REFERENCES stop(id),
    crew_id                 integer NOT NULL REFERENCES crew_member(id),
    originally_assigned_to  integer REFERENCES crew_member(id),  -- target not drawn in ERD
    arrived_at              time,
    finished_at             time,
    completed               boolean
);

-- photo

-- connection to -> stop (id)
-- connection to -> crew_member (id)

CREATE TABLE photo (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_id      integer NOT NULL REFERENCES stop(id),
    crew_id      integer NOT NULL REFERENCES crew_member(id),
    data         bytea,
    description  text,
    created_at   timestamp
);

-- problem

-- connection to -> crew_member (id)
-- connection TO -> STOP (id)

CREATE TABLE problem (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reported_by  integer NOT NULL REFERENCES crew_member(id),
    stop_id      integer NOT NULL REFERENCES stop(id),
    description  text,
    created_at   timestamp
);

-- delivery note

-- connection to -> stop (id)

CREATE TABLE delivery_note (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_id     integer NOT NULL REFERENCES stop(id),
    source_pdf  text,
    date        date,
    number      integer
);

-- cargo

-- connections to -> client (id)
-- connections to -> location (id)

CREATE TABLE cargo (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id    integer NOT NULL REFERENCES client(id),
    location_id  integer NOT NULL REFERENCES location(id),
    typ          text,
    volume       integer
);
