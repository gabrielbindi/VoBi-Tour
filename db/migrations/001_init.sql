-- 001 init.sql
-- creates Tables

CREATE EXTENSION IF NOT EXISTS postgis;

-- Crew-members

CREATE TABLE crew_member (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text,
    last_name       text,
    phone           text,
    service_number  text
);

-- vehicles

CREATE TABLE vehicle (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate   varchar,
    height  integer,     -- cm
    width   integer,     -- cm
    weight  integer      -- kg
);

-- clients

CREATE TABLE client (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   text,
    phone  text
);

-- locations

CREATE TABLE location (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description   varchar,
    geom          geometry(Point, 4326),
    street        text,
    house_number  text,
    zip           text,
    city          text
);

-- tours

CREATE TABLE tour (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     text,
    date     date,
    status   varchar,
    counter  integer
);

-- stops
-- connection to -> tour (id)
-- connection to -> location (id)

CREATE TABLE stop (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id       integer NOT NULL REFERENCES tour(id),
    location_id   integer NOT NULL REFERENCES location(id),
    sequence      integer,
    arrival       time,
    status        varchar,
    is_special    boolean,
    priority      integer,
    special_type  text
);

-- breaks
-- connection to -> tour (id)
-- connection to -> crew_member (id)

CREATE TABLE break (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id  integer NOT NULL REFERENCES tour(id),
    crew_id  integer NOT NULL REFERENCES crew_member(id),
    start    time,
    "end"    time
);

-- tour_vehicle
-- Junction Table

-- connections to -> tour (id)
-- connections to -> vehicle (id)

CREATE TABLE tour_vehicle (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id        integer NOT NULL REFERENCES tour(id),
    vehicle_id     integer NOT NULL REFERENCES vehicle(id),
    assigned_date  date
);

